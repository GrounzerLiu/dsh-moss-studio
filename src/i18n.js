function fill(template, params) {
  if (params === undefined || params === null) return template
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match))
}

/** Fallback used before the locale service is attached, and in tests. */
function localTranslate(key, params) {
  return fill(ZH[key] ?? key, params)
}

let translate = localTranslate
/** @type {{ getSnapshot?: () => { active: string }, subscribe?: (fn: () => void) => () => void } | undefined} */
let service

/**
 * Attach the client locale service: register this namespace's dictionaries and
 * switch translation over to the service, which knows the active language and
 * its fallback chain.
 *
 * @param {{ register: Function, bind: Function }} locale
 * @returns {() => void} disposer that unregisters the dictionaries
 */
export function attachLocale(locale) {
  if (locale === undefined || locale === null || typeof locale.register !== 'function') {
    return () => {}
  }
  const disposeDictionaries = locale.register(NS, { zh: ZH, en: EN })
  service = locale
  translate = typeof locale.bind === 'function' ? locale.bind(NS) : localTranslate
  return () => {
    translate = localTranslate
    service = undefined
    if (typeof disposeDictionaries === 'function') disposeDictionaries()
  }
}

/**
 * Translate one key.
 * @param {string} key
 * @param {Record<string, string | number>} [params]
 */
export function t(key, params) {
  return translate(key, params)
}

/** Subscribe to locale or dictionary changes; returns a disposer. */
export function subscribe(listener) {
  if (typeof service?.subscribe !== 'function') return () => {}
  return service.subscribe(listener)
}

/** Monotonic revision: changes whenever the language or a dictionary changes. */
export function getRevision() {
  return service?.getSnapshot?.()?.revision ?? 0
}

/** Active language id, for locale-aware formatting such as timestamps. */
export function currentLocale() {
  return service?.getSnapshot?.()?.active ?? 'zh'
}
